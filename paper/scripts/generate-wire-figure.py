#!/usr/bin/env python3
"""Generate the Nehemiah field schematic and a codec-checked canonical example."""
from pathlib import Path
import json
import subprocess
import argparse

PAPER = Path(__file__).resolve().parents[1]
SEGMENTS = [
    'message "q" ', 'run "r" ', 'from "a" ', 'to "b" ',
    'version "1" ', 'kind "Info" ', 'payload {"n":3};',
]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--codec', type=Path, help='Optionally check with the built native codec')
    args = parser.parse_args()
    wire = ''.join(SEGMENTS)
    raw = wire.encode('utf-8')
    assert raw.decode('ascii') == wire
    if args.codec:
        response = subprocess.run([str(args.codec), 'parse'], input=wire, text=True,
                                  capture_output=True, check=True)
        decoded = json.loads(response.stdout)
        if not decoded.get('ok'):
            raise RuntimeError(response.stdout)
        encoded = subprocess.run([str(args.codec), 'encode'],
                                 input=json.dumps(decoded['message']), text=True,
                                 capture_output=True, check=True)
        canonical = json.loads(encoded.stdout)
        if canonical.get('text') != wire:
            raise RuntimeError('Illustrated bytes differ from native canonical encoding')
    def tex(text):
        return text.replace('{',r'\{').replace('}',r'\}')
    parts = [
        '% Generated by scripts/generate-wire-figure.py; field widths are schematic.',
        r'\begin{bytefield}[bitwidth=2.9mm,bitheight=10.5mm,boxformatting={\centering\small}]{32}',
        r'\begin{rightwordgroup}{\small Envelope\\fields}',
        r'\bitbox{16}{\texttt{message}\\Message identifier} & \bitbox{16}{\texttt{run}\\Run identifier} \\',
        r'\bitbox{16}{\texttt{from}\\Sender identifier} & \bitbox{16}{\texttt{to}\\Recipient identifier} \\',
        r'\bitbox{12}{\texttt{version}\\\texttt{"1"}} & \bitbox{20}{\texttt{kind}\\Message kind}',
        r'\end{rightwordgroup} \\',
        r'\begin{rightwordgroup}{\small Application\\content}',
        r'\wordbox{1}{\texttt{payload}\\JSON object (variable length)}',
        r'\end{rightwordgroup} \\',
        r'\wordbox{1}{\texttt{;}\quad End of message}',
        r'\end{bytefield}',
        r'\par\medskip',
        r'{\small Field order: left to right, then top to bottom. Widths are schematic.}',
        r'\par\medskip',
        r'\begin{minipage}{.96\textwidth}',
        r'\small Canonical example ('+str(len(raw))+r' octets):\par\smallskip',
        r'{\footnotesize\ttfamily\noindent '+tex(''.join(SEGMENTS[:4]).rstrip())+r'\par',
        r'\noindent '+tex(''.join(SEGMENTS[4:]))+r'}',
        r'\par\smallskip\small A single space joins the displayed lines. The semicolon ends the message.',
        r'\end{minipage}',
    ]
    (PAPER/'figures'/'wire.tex').write_text('\n'.join(parts)+'\n')
    (PAPER/'figures'/'wire.txt').write_bytes(raw)
    print(f'Wrote field schematic and exact {len(raw)}-octet example')

if __name__ == '__main__':
    main()
