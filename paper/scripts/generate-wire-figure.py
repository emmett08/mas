#!/usr/bin/env python3
"""Render exact octets, not an invented binary header, with LaTeX bytefield."""
from pathlib import Path
import json
import subprocess
import argparse

PAPER = Path(__file__).resolve().parents[1]
SEGMENTS = [
    'message "q" ', 'run "r" ', 'from "a" ', 'to "b" ',
    'version "1" ', 'kind "Info" ', 'payload {"n":3};',
]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--codec', type=Path, help='Optionally check with the built native codec')
    args = parser.parse_args()
    wire = ''.join(SEGMENTS)
    raw = wire.encode('utf-8')
    assert raw.decode('ascii') == wire
    if args.codec:
        response = subprocess.run([str(args.codec), 'parse'], input=wire, text=True,
                                  capture_output=True, check=True)
        decoded = json.loads(response.stdout)
        if not decoded.get('ok'):
            raise RuntimeError(response.stdout)
        encoded = subprocess.run([str(args.codec), 'encode'],
                                 input=json.dumps(decoded['message']), text=True,
                                 capture_output=True, check=True)
        canonical = json.loads(encoded.stdout)
        if canonical.get('text') != wire:
            raise RuntimeError('Illustrated bytes differ from native canonical encoding')
    def cell(c):
        return {' ':r'\textvisiblespace', '"':r'\char34{}',
                '{':r'\{', '}':r'\}'}.get(c,c)
    parts = ['% Generated by scripts/generate-wire-figure.py; one cell = one octet.',
             r'\begin{bytefield}[bitwidth=5.3mm,bitheight=6mm,boxformatting={\centering\ttfamily\small}]{16}',
             r'\bitheader{0-15} \\']
    for offset in range(0,len(wire),16):
        parts.append(r'\begin{leftwordgroup}{\normalfont\small '+str(offset)+'}')
        cells = [r'\bitbox{1}{'+cell(c)+'}' for c in wire[offset:offset+16]]
        missing = 16-len(cells)
        if missing:
            cells.append(r'\bitbox[]{'+str(missing)+'}{}')
        parts.append(' & '.join(cells))
        parts.append(r'\end{leftwordgroup}'+(r' \\' if offset+16<len(wire) else ''))
    parts += [r'\end{bytefield}',r'\par\smallskip',
              r'{\small '+str(len(raw))+r' octets; generic application profile; no trailing newline.}']
    (PAPER/'figures'/'wire.tex').write_text('\n'.join(parts)+'\n')
    (PAPER/'figures'/'wire.txt').write_bytes(raw)
    print(f'Wrote exact {len(raw)}-octet figure')

if __name__ == '__main__':
    main()
