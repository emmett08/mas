#!/usr/bin/env python3
"""Derive the observed rehearsal workflow from the retained execution archive."""

import argparse
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prototype-source', type=Path)
    args = parser.parse_args()
    summary = json.loads((PAPER / 'evidence' / 'incident-rehearsal.json').read_text())
    assert summary['schema_version'] == 'mas-paper-incident-rehearsal/1'
    counts = {}
    for arm, row in summary['by_arm'].items():
        n = row['runs']
        values = [row[name] for name in ('generation_effects', 'assessment_effects', 'provider_effects')]
        assert all(value % n == 0 for value in values)
        counts[arm] = (n, *(value // n for value in values))
    procedures = summary['observed_procedures']
    cap = procedures['one_pass']['provider_call_cap']
    assert all(p['provider_call_cap'] == cap and p['invariant_across_retained_runs'] for p in procedures.values())
    assert counts == {'one_pass': (36, 1, 0, 1), 'revision': (36, 2, 2, 4), 'resample': (36, 4, 0, 4)}
    assert sum(n * calls for n, _, _, calls in counts.values()) == summary['verification']['provider_effects']
    header = r'''% Required packages: tikz
% Required TikZ libraries: arrows.meta
% Target width: 145 mm maximum
% Minimum text size: 9 pt
% Colour/greyscale intent: greyscale
% Generated by scripts/generate-incident-figure.py from retained execution records.
'''
    lines = [header, r'''\begin{tikzpicture}[x=1mm,y=1mm,
    every node/.style={font=\fontsize{9}{11}\selectfont,inner sep=0pt},
    flow/.style={-{Latex[length=1.6mm,width=1.2mm]},line width=.5pt,shorten >=.7mm,shorten <=.7mm}]
\node[anchor=west] at (0,16) {Scripted rehearsal: recorded calls};
''']
    xs = [43, 69, 95, 121]
    for i, x in enumerate(xs, 1):
        lines.append(rf'\node at ({x},8) {{Call {i}}};' + '\n')
    labels = {'one_pass': 'One pass', 'revision': 'Revision', 'resample': 'Resample'}
    ys = {'one_pass': 0, 'revision': -22, 'resample': -49}
    for arm, (n, generation, critique, calls) in counts.items():
        y = ys[arm]
        lines.append(rf'\node[anchor=west,font=\fontsize{{9}}{{11}}\selectfont\bfseries] at (0,{y}) {{{labels[arm]}}};' + '\n')
        lines.append(rf'\node[anchor=west] at (0,{y-5}) {{{n} runs, {calls} ' + ('call' if calls == 1 else 'calls') + r'/run};' + '\n')
        actions = [{'generation': 'Generate', 'assessment': 'Critique'}[role] for role in procedures[arm]['call_roles']]
        for i, action in enumerate(actions):
            lines.append(rf'\node ({arm}{i}) at ({xs[i]},{y}) {{{action}}};' + '\n')
        chosen = procedures[arm]['selected_call_index'] - 1
        sx = xs[chosen]
        lines.append(rf'\draw[line width=.6pt] ({sx-8},{y-3}) -- ({sx+8},{y-3});' + '\n')
        selection = 'Selected after call 4' if arm == 'revision' else 'Selected'
        lines.append(rf'\node at ({sx},{y-7}) {{{selection}}};' + '\n')
    lines.append(r'''\draw[flow] (revision0.east) -- (revision1.west);
\draw[flow] (revision1.east) -- (revision2.west);
\draw[flow] (revision2.east) -- (revision3.west);
\node at (82,-17) {feedback};
\draw[flow] (43,-20) -- (43,-11) -- (95,-11) -- (95,-20);
\node[fill=white,inner xsep=1.5mm] at (65,-11) {prior candidate};
\node[anchor=west] at (35,-63) {Same incident input for each resampled generation};
\end{tikzpicture}
''')
    (PAPER / 'figures' / 'incident-revision.tikz.tex').write_text(''.join(lines))
    if args.prototype_source:
        lines = [header, r'''\begin{tikzpicture}[x=22mm,y=1mm,
    every node/.style={font=\fontsize{9}{11}\selectfont,inner sep=0pt}]
\node[anchor=west] at (-1.5,12) {Recorded provider calls per completed run};
''']
        for arm, (n, gen, crit, calls) in counts.items():
            y = {'one_pass': 0, 'revision': -16, 'resample': -32}[arm]
            lines.append(rf'\node[anchor=east] at (-.1,{y}) {{{labels[arm]} ({n} runs)}};' + '\n')
            lines.append(rf'\fill[black!65] (0,{y-3}) rectangle ({gen},{y+3});' + '\n')
            lines.append(rf'\node[text=white] at ({gen/2},{y}) {{{gen} generation' + ('s' if gen > 1 else '') + r'};' + '\n')
            if crit:
                lines.append(rf'\fill[black!15] ({gen},{y-3}) rectangle ({calls},{y+3});' + '\n')
                lines.append(rf'\node at ({gen+crit/2},{y}) {{{crit} critiques}};' + '\n')
        lines.append(r'\draw[line width=.4pt] (0,-40) -- (4,-40);' + '\n')
        for x in range(5):
            lines.append(rf'\draw[line width=.4pt] ({x},-40) -- ({x},-41.5);\node at ({x},-45) {{{x}}};' + '\n')
        lines.append(r'\node at (2,-51) {Provider calls per run, cap = 4};' + '\n' + r'\end{tikzpicture}' + '\n')
        args.prototype_source.write_text(''.join(lines))
    print(json.dumps({'arm_runs': summary['verification']['arm_runs'], 'cap': cap, 'counts': counts}, indent=2))


if __name__ == '__main__':
    main()
